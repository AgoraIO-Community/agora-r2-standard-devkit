"""Generate the fixed terminal font subsets used by the pixel-glasses view.

Uses the same Pillow/LVGL packing as generate-lvgl-font.py. The external
DejaVu Sans Mono Bold input stays read-only and is pinned by SHA256.
The derived fonts are renamed BK7259 Terminal; their Bitstream Vera license
and notices are retained in assets/licenses/TERMINAL_FONT_LICENSE.txt.
"""

import argparse
import hashlib
import subprocess
from pathlib import Path


FONT_SHA256 = "3a3c502eeff669a231549e80df9f7c49de109bafe303170409e905d0b31a38fe"
OUTPUT = Path(__file__).resolve().parent / "pixel_fonts.c"


def rows(values, width=12):
    return "\n".join(
        "    " + ", ".join(values[index : index + width]) + ","
        for index in range(0, len(values), width)
    )


def subset(font_path, size, characters):
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype(str(font_path), size)
    ascent, descent = font.getmetrics()
    bitmap = []
    descriptors = ["    /* Glyph ID 0 is reserved. */\n    {0},"]
    for codepoint in characters:
        character = chr(codepoint)
        x0, y0, x1, y1 = font.getbbox(character, anchor="ls")
        width, height = x1 - x0, y1 - y0
        if height == 0:
            width = 0
        descriptors.append(
            "    /* U+%04X */\n"
            "    { .bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, "
            ".ofs_x = %d, .ofs_y = %d },"
            % (codepoint, len(bitmap), round(font.getlength(character) * 16),
               width, height, x0, -y1)
        )
        if width and height:
            image = Image.new("L", (width, height))
            ImageDraw.Draw(image).text((-x0, -y0), character, font=font,
                                      fill=255, anchor="ls")
            coverage = [(pixel * 15 + 127) // 255 for pixel in image.getdata()]
            if len(coverage) % 2:
                coverage.append(0)
            bitmap.extend((coverage[i] << 4) | coverage[i + 1]
                          for i in range(0, len(coverage), 2))
    name = f"terminal_{size}"
    text = f"""
static const uint8_t {name}_bitmap[] = {{
{rows([f"0x{value:02x}" for value in bitmap])}
}};

static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{
{chr(10).join(descriptors)}
}};

static const uint16_t {name}_unicode[] = {{
{rows([f"0x{codepoint - characters[0]:04x}" for codepoint in characters])}
}};

static const lv_font_fmt_txt_cmap_t {name}_cmaps[] = {{
    {{
        .range_start = {characters[0]},
        .range_length = {characters[-1] - characters[0] + 1},
        .glyph_id_start = 1,
        .unicode_list = {name}_unicode,
        .list_length = {len(characters)},
        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,
    }},
}};

static const lv_font_fmt_txt_dsc_t {name}_dsc = {{
    .glyph_bitmap = {name}_bitmap,
    .glyph_dsc = {name}_glyphs,
    .cmaps = {name}_cmaps,
    .cmap_num = 1,
    .bpp = 4,
}};

const lv_font_t bk7259_terminal_font_{size} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &{name}_dsc,
}};
"""
    print(f"BK7259 Terminal {size}: {len(characters)} glyphs, {len(bitmap)} bitmap bytes")
    return text


def generate(font_path):
    from PIL import __version__ as pillow_version, features

    if hashlib.sha256(font_path.read_bytes()).hexdigest() != FONT_SHA256:
        raise ValueError("Unexpected terminal font revision")
    text = f"""/* SPDX-License-Identifier: Bitstream-Vera */
/* BK7259 Terminal: subsets derived from DejaVu Sans Mono Bold.
 * Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved.
 * Bitstream Vera is a trademark of Bitstream, Inc.
 * DejaVu changes are in public domain.
 * See assets/licenses/TERMINAL_FONT_LICENSE.txt.
 * Generated by display/generate-pixel-font.py.
 * Input SHA256: {FONT_SHA256}
 * Pillow {pillow_version}; FreeType {features.version("freetype2")}; 4 bpp.
 */
#include "lvgl.h"
"""
    text += subset(font_path, 15, list(range(0x20, 0x7F)))
    text += subset(font_path, 16, sorted({ord(c) for c in "</>"}))
    OUTPUT.write_text(text)
    subprocess.run(
        ["clang-format", "-i", "--style={BasedOnStyle: LLVM, IndentWidth: 4, ColumnLimit: 100}",
         str(OUTPUT)],
        check=True,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True)
    generate(parser.parse_args().font)
