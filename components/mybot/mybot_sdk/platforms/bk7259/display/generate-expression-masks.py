"""Rasterize five small geometric A8 masks, not complete expression frames.

Geometry is independently expressed from the user-provided simulator's
src/expressions.js heart(), star(), and geek ellipse dimensions. Rendering uses
fourfold coverage sampling at the R2 9/16 artwork scale. The firmware reads only
the generated immutable bytes; Pillow is a development tool, not a dependency.
"""
import argparse
import hashlib
import math
from pathlib import Path

from PIL import Image, ImageDraw, __version__ as pillow_version

REFERENCE_SHA256 = "1d51ca444e69a39da5b2feedc38d543aea362433184e89a76a825e757b684e31"
OUTPUT = Path(__file__).with_name("pixel_expression_masks.h")
SCALE = 9 / 16
SAMPLES = 4


def cubic(points):
    result = []
    for step in range(129):
        t = step / 128
        r = 1 - t
        result.append(tuple(r**3 * points[0][axis] + 3*r*r*t * points[1][axis]
                            + 3*r*t*t * points[2][axis] + t**3 * points[3][axis]
                            for axis in (0, 1)))
    return result


def ellipse(rx, ry, angle=0):
    cs, sn = math.cos(angle), math.sin(angle)
    result = []
    for step in range(256):
        t = step * math.tau / 256
        x, y = math.cos(t) * rx, math.sin(t) * ry
        result.append((x*cs-y*sn, x*sn+y*cs))
    return result


def shapes():
    size = 55
    heart = cubic([(0,size*.8),(-size*1.25,0),(-size*.65,-size),(0,-size*.35)])
    heart += cubic([(0,-size*.35),(size*.65,-size),(size*1.25,0),(0,size*.8)])[1:]
    star = []
    for step in range(10):
        angle = -math.pi/2 + step*math.pi/5
        radius = 66 * (.43 if step % 2 else 1)
        star.append((math.cos(angle)*radius,math.sin(angle)*radius))
    return {"Heart":heart, "Star":star, "Ellipse":ellipse(38,48),
            "Cheek":ellipse(54,20), "Tear":ellipse(13,23,-.2)}


def generate():
    lines = ["/* SPDX-License-Identifier: MIT */",
             "/* Copyright (c) 2026 Project Contributors */",
             "/* Generated by generate-expression-masks.py; do not edit pixels.",
             f" * Reference expressions.js SHA256: {REFERENCE_SHA256}",
             f" * Pillow {pillow_version}; scale 9/16, 4x coverage, A8 immutable shapes. */",
             "#ifndef BK7259_PIXEL_EXPRESSION_MASKS_H_",
             "#define BK7259_PIXEL_EXPRESSION_MASKS_H_", "",
             "namespace pixel_masks {",
             "struct Mask { lv_image_dsc_t image; int center_x; int center_y; };", ""]
    total = 0
    for name, points in shapes().items():
        points = [(x*SCALE,y*SCALE) for x,y in points]
        x0 = math.floor(min(x for x,y in points))-2
        y0 = math.floor(min(y for x,y in points))-2
        width = math.ceil(max(x for x,y in points))-x0+3
        height = math.ceil(max(y for x,y in points))-y0+3
        image = Image.new("L", (width*SAMPLES,height*SAMPLES))
        ImageDraw.Draw(image).polygon([((x-x0)*SAMPLES,(y-y0)*SAMPLES) for x,y in points],fill=255)
        image = image.resize((width,height),Image.Resampling.LANCZOS)
        data = image.tobytes()
        total += len(data)
        lines += [f"/* {name}: {width}x{height}, {len(data)} bytes. */",
                  f"static const uint8_t k{name}Bytes[] = {{"]
        for index in range(0,len(data),16):
            lines += ["    " + ", ".join(f"0x{value:02x}" for value in data[index:index+16]) + ","]
        lines += ["};", f"static const Mask k{name} = {{",
                  f"    {{ {{ LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_A8, 0, {width}, {height}, {width}, 0 }},",
                  f"      sizeof(k{name}Bytes), k{name}Bytes, nullptr, nullptr }}, {-x0}, {-y0}",
                  "};", ""]
        print(f"{name}: {width}x{height}, {len(data)} bytes")
    lines += [f"constexpr unsigned kTotalBytes = {total};", "} // namespace pixel_masks",
              "#endif /* BK7259_PIXEL_EXPRESSION_MASKS_H_ */", ""]
    print(f"Total: {total} immutable A8 bytes")
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--reference", type=Path, help="Original simulator src/expressions.js")
    group.add_argument("--check", action="store_true", help="Check reproducible generated pixels")
    args = parser.parse_args()
    if args.reference and hashlib.sha256(args.reference.read_bytes()).hexdigest() != REFERENCE_SHA256:
        parser.error("Unexpected simulator geometry revision")
    text = generate()
    if args.check:
        if OUTPUT.read_text() != text:
            raise SystemExit("Generated masks differ; reproduce with the recorded Pillow version")
        print("Expression mask reproduction OK")
    else:
        OUTPUT.write_text(text)
