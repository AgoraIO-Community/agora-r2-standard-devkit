"""Generate or check the fixed MyBot UI vocabulary font.

Adapted from junlon2006/mybot-esp32 scripts/generate-lvgl-font.py.
Input: OFL-licensed SourceHanSansSC-Normal.otf shipped with LVGL.
Usage: python3 generate-lvgl-font.py --font path/to/SourceHanSansSC-Normal.otf
       python3 generate-lvgl-font.py --check
The source font remains an external read-only generation input.
"""

import argparse
import hashlib
import re
import subprocess
from pathlib import Path


FONT_SHA256 = "1ee89e1669362dee13851129c0a8a791a87521eb4148e5efbf5d26596738e25b"
DIRECTORY = Path(__file__).resolve().parent
VIEW = DIRECTORY / "lvgl_view.cc"
OUTPUT = DIRECTORY / "lvgl_fonts.c"


def codepoints():
    return sorted(set(range(0x20, 0x7F)) | {ord(c) for c in VIEW.read_text() if ord(c) > 127})


def check():
    glyphs = {int(value, 16) for value in re.findall(r"/\* U\+([0-9A-F]+) \*/", OUTPUT.read_text())}
    missing = sorted(set(codepoints()) - glyphs)
    if missing:
        raise ValueError("Missing UI glyphs: " + ", ".join(f"U+{value:04X}" for value in missing))
    print(f"Glyph coverage OK: {len(codepoints())} UI glyphs")


def rows(values, width=12):
    return "\n".join(
        "    " + ", ".join(values[index : index + width]) + ","
        for index in range(0, len(values), width)
    )


def generate(font_path):
    from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version, features

    if hashlib.sha256(font_path.read_bytes()).hexdigest() != FONT_SHA256:
        raise ValueError("Unexpected font revision; verify its provenance and license first")
    font = ImageFont.truetype(str(font_path), 20)
    characters = codepoints()
    missing = bytes(font.getmask("\u0378"))
    bitmap = []
    descriptors = ["    /* Glyph ID 0 is reserved. */\n    {0},"]
    ascent = descent = 0
    for codepoint in characters:
        character = chr(codepoint)
        if bytes(font.getmask(character)) == missing:
            raise ValueError(f"Missing source font glyph U+{codepoint:04X}")
        x0, y0, x1, y1 = font.getbbox(character, anchor="ls")
        width, height = x1 - x0, y1 - y0
        if height == 0:
            width = 0
        advance = round(font.getlength(character) * 16)
        descriptors.append(
            "    /* U+%04X */\n"
            "    { .bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, "
            ".ofs_x = %d, .ofs_y = %d },"
            % (codepoint, len(bitmap), advance, width, height, x0, -y1)
        )
        if width and height:
            image = Image.new("L", (width, height))
            ImageDraw.Draw(image).text((-x0, -y0), character, font=font, fill=255, anchor="ls")
            coverage = [(pixel * 15 + 127) // 255 for pixel in image.getdata()]
            if len(coverage) % 2:
                coverage.append(0)
            bitmap.extend((coverage[i] << 4) | coverage[i + 1] for i in range(0, len(coverage), 2))
            ascent = max(ascent, -y0)
            descent = max(descent, y1)
    text = f"""/* SPDX-License-Identifier: OFL-1.1 */
/* MyBot UI Sans: 20 px, 4 bpp subset of Source Han Sans SC Normal.
 * Copyright 2014-2021 Adobe (http://www.adobe.com/).
 * See LVGL_VIEW_FONT_LICENSE.txt. Generated by display/generate-lvgl-font.py.
 * Input SHA256: {FONT_SHA256}
 * Pillow {pillow_version}; FreeType {features.version("freetype2")}; {len(characters)} glyphs.
 */
#include "lvgl.h"

static const uint8_t glyph_bitmap[] = {{
{rows([f"0x{value:02x}" for value in bitmap])}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(descriptors)}
}};

static const uint16_t unicode_list[] = {{
{rows([f"0x{codepoint - 0x20:04x}" for codepoint in characters])}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = 0x20,
        .range_length = {characters[-1] - 0x20 + 1},
        .glyph_id_start = 1,
        .unicode_list = unicode_list,
        .list_length = {len(characters)},
        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,
    }},
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .cmap_num = 1,
    .bpp = 4,
}};

const lv_font_t mybot_lvgl_font_20 = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent + 2},
    .base_line = {descent + 1},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &font_dsc,
}};
"""
    OUTPUT.write_text(text)
    subprocess.run(
        ["clang-format", "-i", "--style={BasedOnStyle: LLVM, IndentWidth: 4, ColumnLimit: 100}",
         str(OUTPUT)],
        check=True,
    )
    print(f"Generated {len(characters)} glyphs, {len(bitmap)} bitmap bytes")
    check()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--font", type=Path)
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        check()
    else:
        generate(args.font)
